async function cmdCompose(args) {
  const pkg = await loadLib("pkg.mjs");
  if (!pkg) {
    console.log("compose: pkg not available yet (lib/pkg.mjs not found)");
    return;
  }
  const dir = process.cwd();
  const loaded = pkg.loadPackage(dir);
  const spec = loaded.workspace;
  if (!spec) {
    console.log("compose: no ace spec found in package.json");
    return;
  }

  // Resolve extends from local registry if present
  const reg = await loadLib("registry.mjs");
  const deps = [];
  if (Array.isArray(spec.extends) && reg) {
    for (const name of spec.extends) {
      const info = reg.infoLocal(name.replace(/^@ace\//, ""));
      if (info) deps.push(info);
    }
  }

  const composed = pkg.compose(spec, deps);
  if (args.includes("--json")) {
    printJson(composed);
  } else {
    // Simple YAML output (key: value, nested via indent)
    console.log(JSON.stringify(composed, null, 2));
  }
}

async function cmdDoctor(args) {
  const pkg = await loadLib("pkg.mjs");
  if (!pkg || typeof pkg.doctor !== "function") {
    console.log("doctor: not available yet (lib/pkg.mjs doctor not implemented)");
    return;
  }
  const result = pkg.doctor(process.cwd());
  if (args.includes("--json")) {
    printJson(result);
    return;
  }
  console.log(`Doctor: ${result.ok ? "OK" : "FAIL"}`);
  for (const check of result.checks || []) {
    console.log(`  ${check.ok ? "✓" : "✗"} ${check.name}: ${check.detail || ""}`);
  }
  for (const w of result.warnings || []) {
    console.log(`  ! ${w}`);
  }
}

async function cmdUpdate() {
  const pkg = await loadLib("pkg.mjs");
  if (!pkg || typeof pkg.resolveDependencies !== "function") {
    console.log("update: not available yet (lib/pkg.mjs resolveDependencies not implemented)");
    return;
  }
  const dir = process.cwd();
  const loaded = pkg.loadPackage(dir);
  const manifest = loaded.manifest;
  const reg = await loadLib("registry.mjs");
  const result = pkg.resolveDependencies(manifest, reg);
  if (!result.ok) {
    console.log("update: dependency conflicts detected:");
    for (const c of result.conflicts || []) console.log(`  ${c}`);
    return;
  }
  console.log(`update: resolved ${Object.keys(result.graph || {}).length} package(s)`);
  for (const [name, info] of Object.entries(result.graph || {})) {
    console.log(`  ${name}@${info.version}`);
  }
}

async function cmdUninstall(args) {
  const name = args[0];
  if (!name) { console.log("usage: ace uninstall <pkg>"); return; }
  const pkg = await loadLib("pkg.mjs");
  if (!pkg) {
    console.log("uninstall: pkg not available yet (lib/pkg.mjs not found)");
    return;
  }
  const dir = process.cwd();
  const loaded = pkg.loadPackage(dir);
  const manifest = loaded.manifest;
  if (!manifest.dependencies || !manifest.dependencies[name]) {
    console.log(`uninstall: "${name}" is not a dependency`);
    return;
  }
  delete manifest.dependencies[name];
  writeJson(path.join(dir, "package.json"), manifest);
  console.log(`Uninstalled ${name}.`);
}

async function cmdSecretSet(args) {
  const name = args[0];
  if (!name) { console.log("usage: ace secret set <name>"); return; }
  const dir = process.cwd();
  const secretsDir = path.join(dir, ".ace", "secrets");
  ensureDir(secretsDir);

  // Read value from stdin without echoing
  const value = await new Promise((resolve) => {
    if (process.stdin.isTTY) {
      // Interactive: use readline with muted output
      import("node:readline").then(({ createInterface }) => {
        const rl = createInterface({ input: process.stdin, output: process.stdout });
        rl.question(`Enter value for ${name}: `, (answer) => {
          rl.close();
          resolve(answer.trim());
        });
      });
    } else {
      // Piped: read all stdin
      let buf = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (chunk) => { buf += chunk; });
      process.stdin.on("end", () => resolve(buf.trim()));
    }
  });

  if (!value) {
    console.log("secret set: empty value — aborted");
    return;
  }
  fs.writeFileSync(path.join(secretsDir, name), value + "\n", { mode: 0o600 });
  console.log(`Secret "${name}" stored in .ace/secrets/${name}`);
}

async function cmdActivity() {
  const rt = await loadLib("runtime.mjs");
  if (!rt) {
    console.log("activity: runtime not available yet (lib/runtime.mjs not found)");
    return;
  }
  const dir = process.cwd();
  const agents = rt.getAgents(dir);
  const tasks = rt.getTasks(dir);

  const working = agents.filter((a) => a.status === "working");
  const idle = agents.filter((a) => a.status === "idle");
  const queued = tasks.filter((t) => t.status === "queued" || t.status === "pending");

  console.log("NOW:");
  if (!working.length) console.log("  (no agents working)");
  for (const a of working) console.log(`  ${a.id} (${a.role}) — task: ${a.task || "—"}`);

  console.log("NEXT:");
  if (!queued.length) console.log("  (no tasks queued)");
  for (const t of queued) console.log(`  ${t.id} — ${t.title} (priority: ${t.priority || "—"})`);

  if (idle.length) console.log(`IDLE: ${idle.length} agent(s)`);
}

