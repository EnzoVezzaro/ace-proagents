function readJson(p) {
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
}

function writeJson(p, obj) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, JSON.stringify(obj, null, 2) + "\n", "utf8");
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

function printJson(obj) {
  console.log(JSON.stringify(obj, null, 2));
}

function printTable(rows, columns) {
  if (!rows.length) { console.log("  (none)"); return; }
  const widths = columns.map((c) => Math.max(c.header.length, ...rows.map((r) => String(r[c.key] ?? "").length)));
  const header = columns.map((c, i) => c.header.padEnd(widths[i])).join("  ");
  console.log("  " + header);
  console.log("  " + widths.map((w) => "-".repeat(w)).join("  "));
  for (const row of rows) {
    console.log("  " + columns.map((c, i) => String(row[c.key] ?? "").padEnd(widths[i])).join("  "));
  }
}

function gitInfo(dir) {
  try {
    const branch = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { cwd: dir, encoding: "utf8" }).trim();
    const commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: dir, encoding: "utf8" }).trim();
    return { branch, commit };
  } catch {
    return { branch: null, commit: null };
  }
}

function getTargetDir(args) {
  const nameIdx = args.indexOf("--name");
  if (nameIdx !== -1 && args[nameIdx + 1]) return args[nameIdx + 1];
  return null;
}

